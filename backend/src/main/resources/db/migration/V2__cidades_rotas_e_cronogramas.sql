-- ============================================================
-- SIMUL - V2
-- Estrutura da coleta: cidades, rotas, bairros (áreas atendidas)
-- e cronogramas.
--
-- Regras garantidas pelo banco:
--   * cada rota pertence a uma única cidade;
--   * o bairro só fica numa rota da própria cidade (FK composta);
--   * bairro único por cidade (sem diferenciar maiúsculas);
--   * uma coleta ativa por rota, dia e turno;
--   * horário da coleta opcional: as prefeituras costumam informar
--     só o turno, e nada é inventado.
-- ============================================================

CREATE TABLE cidades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    uf VARCHAR(2) NOT NULL,
    fonte TEXT,

    -- Faixa média de cada turno, informada pela operadora. É mostrada
    -- como horário aproximado e usada como início do turno no lembrete.
    diurno_inicio TIME,
    diurno_fim TIME,
    noturno_inicio TIME,
    noturno_fim TIME,
    fonte_turnos VARCHAR(255),

    data_criacao TIMESTAMP NOT NULL,
    data_atualizacao TIMESTAMP NOT NULL,

    CONSTRAINT ck_cidades_diurno_completo CHECK ((diurno_inicio IS NULL) = (diurno_fim IS NULL)),
    CONSTRAINT ck_cidades_noturno_completo CHECK ((noturno_inicio IS NULL) = (noturno_fim IS NULL))
);

CREATE UNIQUE INDEX uk_cidades_nome_upper ON cidades (UPPER(nome));

-- Rota = grupo de bairros com os mesmos dias e turnos (não é o trajeto do caminhão).
CREATE TABLE rotas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cidade_id BIGINT NOT NULL,
    nome VARCHAR(120) NOT NULL,
    descricao VARCHAR(255),
    ativo BOOLEAN NOT NULL,
    tipo_coleta VARCHAR(20) NOT NULL,
    fonte VARCHAR(255),
    data_criacao TIMESTAMP NOT NULL,
    data_atualizacao TIMESTAMP NOT NULL,

    CONSTRAINT fk_rotas_cidade FOREIGN KEY (cidade_id) REFERENCES cidades(id),
    CONSTRAINT ck_rotas_tipo_coleta CHECK (tipo_coleta IN ('SELETIVA', 'CONVENCIONAL', 'NAO_INFORMADO')),
    -- Alvo da FK composta dos bairros (rota + cidade).
    CONSTRAINT uk_rotas_id_cidade UNIQUE (id, cidade_id)
);

CREATE INDEX idx_rotas_cidade_id ON rotas (cidade_id);

CREATE TABLE areas_atendidas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cidade_id BIGINT NOT NULL,
    bairro VARCHAR(120) NOT NULL,
    rota_id BIGINT NOT NULL,
    geometria_geojson TEXT,

    CONSTRAINT fk_areas_atendidas_cidade FOREIGN KEY (cidade_id) REFERENCES cidades(id),
    -- A rota do bairro precisa ser da mesma cidade do bairro.
    CONSTRAINT fk_areas_atendidas_rota_mesma_cidade
        FOREIGN KEY (rota_id, cidade_id) REFERENCES rotas (id, cidade_id)
);

CREATE UNIQUE INDEX uk_areas_atendidas_cidade_bairro ON areas_atendidas (cidade_id, UPPER(bairro));
CREATE INDEX idx_areas_atendidas_cidade_id ON areas_atendidas (cidade_id);
CREATE INDEX idx_areas_atendidas_rota_id ON areas_atendidas (rota_id);

CREATE TABLE cronogramas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rota_id BIGINT NOT NULL,
    dia_semana VARCHAR(10) NOT NULL,
    turno VARCHAR(15) NOT NULL,
    horario_inicio TIME(0),
    horario_fim TIME(0),
    ativo BOOLEAN NOT NULL,
    data_criacao TIMESTAMP NOT NULL,
    data_atualizacao TIMESTAMP NOT NULL,

    CONSTRAINT fk_cronogramas_rota FOREIGN KEY (rota_id) REFERENCES rotas(id),
    CONSTRAINT ck_cronogramas_dia_semana
        CHECK (dia_semana IN ('SEGUNDA', 'TERCA', 'QUARTA', 'QUINTA', 'SEXTA', 'SABADO', 'DOMINGO')),
    CONSTRAINT ck_cronogramas_turno CHECK (turno IN ('DIURNO', 'NOTURNO', 'NAO_INFORMADO')),
    -- Horário completo ou nenhum (só o turno).
    CONSTRAINT ck_cronogramas_horario_completo CHECK ((horario_inicio IS NULL) = (horario_fim IS NULL)),
    -- Fim antes do início é permitido: coleta que passa da meia-noite.
    CONSTRAINT ck_cronogramas_horarios_diferentes CHECK (horario_inicio <> horario_fim)
);

CREATE INDEX idx_cronogramas_rota_id ON cronogramas (rota_id);

-- Uma coleta ativa por rota, dia e turno (o mesmo dia pode ter coleta diurna e noturna).
CREATE UNIQUE INDEX uk_cronogramas_rota_dia_turno_ativo
    ON cronogramas (rota_id, dia_semana, turno)
    WHERE ativo;
