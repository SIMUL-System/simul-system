-- ============================================================
-- SIMUL - V24
-- Cidades, turno da coleta e tipo de coleta.
--
-- 1. Cria a tabela "cidades" a partir das cidades que já existem
--    nas áreas atendidas.
-- 2. Cada rota passa a pertencer a uma única cidade (cidade_id).
-- 3. Cada bairro aponta para a cidade por id, e o banco garante
--    que a rota do bairro é da MESMA cidade (FK composta).
-- 4. Cronograma ganha "turno" (DIURNO, NOTURNO, NAO_INFORMADO) e
--    o horário passa a ser opcional: fontes que informam só o
--    turno não precisam de horário inventado.
-- 5. Rota ganha tipo de coleta (SELETIVA ou NAO_INFORMADO) e fonte.
--
-- Nenhum id, bairro, contorno ou preferência é apagado.
-- ============================================================

-- ------------------------------------------------------------
-- 1. Cidades
-- ------------------------------------------------------------
CREATE TABLE cidades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    uf VARCHAR(2) NOT NULL,
    fonte TEXT,
    data_criacao TIMESTAMP NOT NULL,
    data_atualizacao TIMESTAMP NOT NULL
);

CREATE UNIQUE INDEX uk_cidades_nome_upper
    ON cidades (UPPER(nome));

INSERT INTO cidades (nome, uf, data_criacao, data_atualizacao)
SELECT DISTINCT ON (UPPER(TRIM(a.cidade)))
    TRIM(a.cidade),
    'GO',
    CURRENT_TIMESTAMP,
    CURRENT_TIMESTAMP
FROM areas_atendidas a
ORDER BY UPPER(TRIM(a.cidade)), TRIM(a.cidade);

-- ------------------------------------------------------------
-- 2. Rota -> cidade
-- ------------------------------------------------------------
ALTER TABLE rotas
    ADD COLUMN cidade_id BIGINT,
    ADD COLUMN tipo_coleta VARCHAR(20),
    ADD COLUMN fonte VARCHAR(255);

-- Uma rota com bairros de mais de uma cidade não tem como ser
-- classificada sem escolher arbitrariamente: a migration para.
DO $$
DECLARE
    misturada RECORD;
BEGIN
    SELECT r.id, r.nome INTO misturada
    FROM rotas r
    JOIN areas_atendidas a ON a.rota_id = r.id
    GROUP BY r.id, r.nome
    HAVING COUNT(DISTINCT UPPER(TRIM(a.cidade))) > 1
    LIMIT 1;

    IF FOUND THEN
        RAISE EXCEPTION
            'A rota % (%) tem bairros de mais de uma cidade. Separe os bairros pelo painel antes de aplicar a V24.',
            misturada.id, misturada.nome;
    END IF;
END $$;

-- Cidade dos bairros da rota
UPDATE rotas r
SET cidade_id = c.id
FROM (
    SELECT DISTINCT a.rota_id, UPPER(TRIM(a.cidade)) AS cidade
    FROM areas_atendidas a
) origem
JOIN cidades c ON UPPER(c.nome) = origem.cidade
WHERE origem.rota_id = r.id;

-- Rota sem bairros: pelo começo do nome ("Senador Canedo - ...")
UPDATE rotas r
SET cidade_id = c.id
FROM cidades c
WHERE r.cidade_id IS NULL
  AND UPPER(r.nome) LIKE UPPER(c.nome) || ' - %';

-- Rota vazia (sem bairros) e sem a cidade no nome: fica na cidade
-- com mais bairros, e a fonte registra que a cidade foi atribuída
-- pela migração, para conferência no painel. Nada é apagado.
UPDATE rotas
SET cidade_id = (
        SELECT a.cidade_id_origem
        FROM (
            SELECT c.id AS cidade_id_origem, COUNT(*) AS total
            FROM areas_atendidas a
            JOIN cidades c ON UPPER(c.nome) = UPPER(TRIM(a.cidade))
            GROUP BY c.id
            ORDER BY total DESC, c.id
            LIMIT 1
        ) a
    ),
    fonte = 'Cidade atribuída automaticamente pela V24 (rota sem bairros). Confira no painel.'
WHERE cidade_id IS NULL;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM rotas WHERE cidade_id IS NULL) THEN
        RAISE EXCEPTION
            'Há rotas, mas nenhum bairro cadastrado para descobrir a cidade delas.';
    END IF;
END $$;

-- As fontes de Senador Canedo não dizem se a coleta é a seletiva:
-- tudo o que já existia fica NAO_INFORMADO (a V25 detalha as fontes).
UPDATE rotas SET tipo_coleta = 'NAO_INFORMADO';

ALTER TABLE rotas
    ALTER COLUMN cidade_id SET NOT NULL,
    ALTER COLUMN tipo_coleta SET NOT NULL,
    ADD CONSTRAINT fk_rotas_cidade FOREIGN KEY (cidade_id) REFERENCES cidades(id),
    ADD CONSTRAINT ck_rotas_tipo_coleta CHECK (tipo_coleta IN ('SELETIVA', 'NAO_INFORMADO')),
    ADD CONSTRAINT uk_rotas_id_cidade UNIQUE (id, cidade_id);

CREATE INDEX idx_rotas_cidade_id ON rotas (cidade_id);

-- ------------------------------------------------------------
-- 3. Bairro -> cidade (por id), sempre a mesma da rota
-- ------------------------------------------------------------
ALTER TABLE areas_atendidas
    ADD COLUMN cidade_id BIGINT;

UPDATE areas_atendidas a
SET cidade_id = c.id
FROM cidades c
WHERE UPPER(c.nome) = UPPER(TRIM(a.cidade));

ALTER TABLE areas_atendidas
    ALTER COLUMN cidade_id SET NOT NULL,
    ADD CONSTRAINT fk_areas_atendidas_cidade FOREIGN KEY (cidade_id) REFERENCES cidades(id),
    -- A rota do bairro precisa ser da mesma cidade do bairro.
    ADD CONSTRAINT fk_areas_atendidas_rota_mesma_cidade
        FOREIGN KEY (rota_id, cidade_id) REFERENCES rotas (id, cidade_id);

DROP INDEX IF EXISTS uk_areas_atendidas_cidade_bairro;

CREATE UNIQUE INDEX uk_areas_atendidas_cidade_bairro
    ON areas_atendidas (cidade_id, UPPER(bairro));

CREATE INDEX idx_areas_atendidas_cidade_id ON areas_atendidas (cidade_id);

-- O nome da cidade agora vem da tabela "cidades".
ALTER TABLE areas_atendidas
    DROP COLUMN cidade;

-- ------------------------------------------------------------
-- 4. Turno no cronograma; horário opcional
-- ------------------------------------------------------------
ALTER TABLE cronogramas
    ADD COLUMN turno VARCHAR(15);

UPDATE cronogramas
SET turno = CASE
    WHEN EXTRACT(HOUR FROM horario_inicio) >= 18 OR EXTRACT(HOUR FROM horario_inicio) < 6 THEN 'NOTURNO'
    ELSE 'DIURNO'
END;

ALTER TABLE cronogramas
    ALTER COLUMN turno SET NOT NULL,
    ALTER COLUMN horario_inicio DROP NOT NULL,
    ALTER COLUMN horario_fim DROP NOT NULL,
    ADD CONSTRAINT ck_cronogramas_turno CHECK (turno IN ('DIURNO', 'NOTURNO', 'NAO_INFORMADO')),
    ADD CONSTRAINT ck_cronogramas_horario_completo
        CHECK ((horario_inicio IS NULL) = (horario_fim IS NULL));

-- Os horários 06:00-18:00 e 18:00-23:59 da carga de Senador Canedo
-- (V15/V18) não vêm da prefeitura, que informa só "diurno" e
-- "noturno". Eles viram turno sem horário. Horários diferentes
-- desses (editados no painel) continuam como estão.
UPDATE cronogramas c
SET horario_inicio = NULL,
    horario_fim = NULL
FROM rotas r
JOIN cidades cid ON cid.id = r.cidade_id
WHERE c.rota_id = r.id
  AND UPPER(cid.nome) = 'SENADOR CANEDO'
  AND (
        (c.turno = 'DIURNO' AND c.horario_inicio = TIME '06:00' AND c.horario_fim = TIME '18:00')
     OR (c.turno = 'NOTURNO' AND c.horario_inicio = TIME '18:00' AND c.horario_fim = TIME '23:59')
  );

-- Uma coleta ativa por rota, dia e TURNO (um bairro pode ter
-- coleta de dia e de noite no mesmo dia).
DROP INDEX IF EXISTS uk_cronogramas_rota_dia_ativo;

CREATE UNIQUE INDEX uk_cronogramas_rota_dia_turno_ativo
    ON cronogramas (rota_id, dia_semana, turno)
    WHERE ativo;
