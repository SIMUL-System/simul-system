-- Conteúdo da página "Quem somos", editável no painel admin:
-- texto sobre o projeto e a instituição, fotos da faculdade e
-- integrantes da equipe (com foto e descrição).
--
-- As imagens ficam no próprio banco (BYTEA): o disco da Render
-- gratuita é apagado a cada deploy, então arquivos soltos no
-- servidor se perderiam.
-- ============================================================

CREATE TABLE imagens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_conteudo VARCHAR(30) NOT NULL,
    dados BYTEA NOT NULL,
    tamanho_bytes INTEGER NOT NULL,
    data_criacao TIMESTAMP NOT NULL,

    CONSTRAINT ck_imagens_tipo
        CHECK (tipo_conteudo IN ('image/jpeg', 'image/png', 'image/webp')),
    CONSTRAINT ck_imagens_tamanho
        CHECK (tamanho_bytes > 0 AND tamanho_bytes <= 3145728)
);

-- Uma linha só, com os textos da página.
CREATE TABLE conteudo_institucional (
    id BIGINT PRIMARY KEY,
    sobre_projeto TEXT NOT NULL,
    instituicao_nome VARCHAR(150) NOT NULL,
    instituicao_texto TEXT NOT NULL,
    curso VARCHAR(150) NOT NULL,
    data_atualizacao TIMESTAMP NOT NULL,

    CONSTRAINT ck_conteudo_institucional_unico CHECK (id = 1)
);

CREATE TABLE fotos_instituicao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    imagem_id BIGINT NOT NULL UNIQUE,
    legenda VARCHAR(200) NOT NULL,
    ordem INTEGER NOT NULL DEFAULT 0,

    CONSTRAINT fk_fotos_instituicao_imagem
        FOREIGN KEY (imagem_id) REFERENCES imagens(id) ON DELETE CASCADE
);

CREATE TABLE integrantes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    funcao VARCHAR(120) NOT NULL,
    descricao TEXT NOT NULL,
    foto_id BIGINT,
    link VARCHAR(255),
    ordem INTEGER NOT NULL DEFAULT 0,
    data_criacao TIMESTAMP NOT NULL,
    data_atualizacao TIMESTAMP NOT NULL,

    CONSTRAINT fk_integrantes_foto
        FOREIGN KEY (foto_id) REFERENCES imagens(id) ON DELETE SET NULL
);

