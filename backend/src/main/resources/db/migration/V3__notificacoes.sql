-- ============================================================
-- SIMUL - V3
-- Lembretes: preferência do morador, histórico de envios (com
-- deduplicação e novas tentativas) e inscrições de Web Push.
-- ============================================================

-- A preferência guarda o BAIRRO; a rota vem dele. Ao mover um
-- bairro de rota, os lembretes seguem a rota nova sozinhos.
CREATE TABLE preferencias_notificacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL UNIQUE,
    area_atendida_id BIGINT NOT NULL,
    email_ativo BOOLEAN NOT NULL,
    web_push_ativo BOOLEAN NOT NULL,
    antecedencia_horas INTEGER NOT NULL,
    data_criacao TIMESTAMP NOT NULL,
    data_atualizacao TIMESTAMP NOT NULL,

    CONSTRAINT fk_preferencias_notificacao_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(id),
    CONSTRAINT fk_preferencias_notificacao_area_atendida
        FOREIGN KEY (area_atendida_id) REFERENCES areas_atendidas(id),
    CONSTRAINT ck_preferencias_notificacao_antecedencia
        CHECK (antecedencia_horas BETWEEN 0 AND 72)
);

CREATE INDEX idx_preferencias_notificacao_area_atendida_id ON preferencias_notificacao (area_atendida_id);

-- Um lembrete por usuário, rota, coleta e canal (a restrição única
-- impede envio duplicado mesmo com o agendador rodando duas vezes).
CREATE TABLE historico_notificacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    rota_id BIGINT NOT NULL,
    data_hora_coleta TIMESTAMP NOT NULL,
    canal VARCHAR(30) NOT NULL,
    status VARCHAR(30) NOT NULL,
    data_envio TIMESTAMP,
    mensagem_erro VARCHAR(500),
    numero_tentativas INTEGER NOT NULL,
    proxima_tentativa TIMESTAMP,
    data_criacao TIMESTAMP NOT NULL,
    data_atualizacao TIMESTAMP NOT NULL,

    CONSTRAINT fk_historico_notificacoes_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(id),
    CONSTRAINT fk_historico_notificacoes_rota FOREIGN KEY (rota_id) REFERENCES rotas(id),
    CONSTRAINT uk_historico_notificacao_ocorrencia_canal
        UNIQUE (usuario_id, rota_id, data_hora_coleta, canal),
    CONSTRAINT ck_historico_notificacoes_canal CHECK (canal IN ('EMAIL', 'WEB_PUSH')),
    CONSTRAINT ck_historico_notificacoes_status
        CHECK (status IN ('PENDENTE', 'ENVIADO', 'FALHA', 'CANCELADO')),
    CONSTRAINT ck_historico_notificacoes_numero_tentativas
        CHECK (numero_tentativas BETWEEN 0 AND 3)
);

CREATE INDEX idx_historico_notificacoes_rota_id ON historico_notificacoes (rota_id);
CREATE INDEX idx_historico_notificacoes_retry ON historico_notificacoes (status, proxima_tentativa);

-- Inscrições do navegador para Web Push.
CREATE TABLE push_subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    endpoint TEXT NOT NULL,
    p256dh TEXT NOT NULL,
    auth TEXT NOT NULL,
    data_criacao TIMESTAMP NOT NULL,
    data_atualizacao TIMESTAMP NOT NULL,

    CONSTRAINT fk_push_subscription_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE,
    CONSTRAINT uk_push_subscription_endpoint UNIQUE (endpoint)
);

CREATE INDEX idx_push_subscriptions_usuario_id ON push_subscriptions (usuario_id);
