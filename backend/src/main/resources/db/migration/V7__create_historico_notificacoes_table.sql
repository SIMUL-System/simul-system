CREATE TABLE historico_notificacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    usuario_id BIGINT NOT NULL,
    rota_id BIGINT NOT NULL,

    data_hora_coleta TIMESTAMP NOT NULL,

    canal VARCHAR(30) NOT NULL,
    status VARCHAR(30) NOT NULL,

    data_envio TIMESTAMP,
    mensagem_erro VARCHAR(500),

    data_criacao TIMESTAMP NOT NULL,
    data_atualizacao TIMESTAMP NOT NULL,

    CONSTRAINT fk_historico_notificacoes_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES usuarios(id),

    CONSTRAINT fk_historico_notificacoes_rota
        FOREIGN KEY (rota_id)
        REFERENCES rotas(id),

    CONSTRAINT uk_historico_notificacao_ocorrencia_canal
        UNIQUE (
            usuario_id,
            rota_id,
            data_hora_coleta,
            canal
        )
);