-- ============================================================
-- SIMUL - V1
-- Usuários e tokens de acesso (confirmação de e-mail e
-- recuperação de senha).
--
-- O e-mail fica cifrado (AES-GCM) na coluna "email"; a busca e a
-- unicidade usam "email_hash" (HMAC do e-mail normalizado). Os
-- dois são calculados pela aplicação com SIMUL_DADOS_CHAVE.
-- ============================================================

CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    email VARCHAR(512) NOT NULL,
    email_hash VARCHAR(64) NOT NULL,
    senha VARCHAR(255) NOT NULL,
    perfil VARCHAR(20) NOT NULL,
    ativo BOOLEAN NOT NULL,
    email_verificado BOOLEAN NOT NULL DEFAULT FALSE,
    termos_aceitos_em TIMESTAMP,
    termos_versao VARCHAR(20),
    data_criacao TIMESTAMP NOT NULL,
    data_atualizacao TIMESTAMP NOT NULL,

    CONSTRAINT uk_usuarios_email_hash UNIQUE (email_hash),
    CONSTRAINT ck_usuarios_perfil CHECK (perfil IN ('USUARIO', 'ADMIN'))
);

-- Link de confirmação de e-mail (guarda só o hash do token).
CREATE TABLE tokens_verificacao_email (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    data_expiracao TIMESTAMP NOT NULL,
    utilizado BOOLEAN NOT NULL DEFAULT FALSE,
    data_utilizacao TIMESTAMP,
    data_criacao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_token_verificacao_email_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE
);

CREATE INDEX idx_token_verificacao_email_usuario_id ON tokens_verificacao_email (usuario_id);
CREATE INDEX idx_token_verificacao_email_expiracao ON tokens_verificacao_email (data_expiracao);

-- Link de recuperação de senha (guarda só o hash do token).
CREATE TABLE tokens_recuperacao_senha (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    data_expiracao TIMESTAMP NOT NULL,
    utilizado BOOLEAN NOT NULL DEFAULT FALSE,
    data_utilizacao TIMESTAMP,
    data_criacao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_token_recuperacao_senha_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE
);

CREATE INDEX idx_token_recuperacao_senha_usuario_id ON tokens_recuperacao_senha (usuario_id);
CREATE INDEX idx_token_recuperacao_senha_expiracao ON tokens_recuperacao_senha (data_expiracao);
